CREATE DATABASE IF NOT EXISTS konsort_scada CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE konsort_scada;

CREATE TABLE IF NOT EXISTS devices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 device_id VARCHAR(100) NOT NULL UNIQUE,
 name VARCHAR(255) NOT NULL,
 protocol VARCHAR(50) NOT NULL,
 endpoint VARCHAR(500) NULL,
 host VARCHAR(255) NULL,
 port INT NULL,
 unit_id INT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tags (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 device_id VARCHAR(100) NOT NULL,
 tag_name VARCHAR(255) NOT NULL,
 data_type VARCHAR(50) NOT NULL,
 source_address VARCHAR(1000) NOT NULL,
 history_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 history_mode VARCHAR(50) NOT NULL DEFAULT 'disabled',
 history_interval_ms INT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE KEY uq_tags_device_tag (device_id, tag_name)
);
